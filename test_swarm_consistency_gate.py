class GateUnitTests(unittest.TestCase):
    def setUp(self):
        self.members = {i: SwarmIdentity(i) for i in range(1, 5)}
        self.roster = {i: x.public_bytes() for i, x in self.members.items()}
        self.positions = {
            1: (60., 0., 10.), 2: (0., 0., 10.),
            3: (100., 0., 10.), 4: (130., 0., 10.),
        }
        self.health = {i: HealthReport(90., 100., 95.) for i in self.members}
        self.tasks = {"inspection": (1., 0., 10.)}
        self.t = 1000.

    def evaluate(self, *, policy=None, witnesses=None, positions=None,
                 health=None, pseen=None, hseen=None, prior=None, epoch=1):
        return consistency_gated_allocate(
            positions=positions if positions is not None else self.positions,
            health=health if health is not None else self.health,
            health_seen_at=hseen if hseen is not None else {i: self.t for i in self.members},
            position_seen_at=pseen if pseen is not None else {i: self.t for i in self.members},
            now=self.t, tasks=self.tasks, roster=self.roster, epoch=epoch,
            policy=policy or ConsistencyPolicy(), witnesses=witnesses,
            previous_positions=prior,
        )

    @staticmethod
    def assigned(result):
        ids = [node for node, values in result["allocations"].items() if values]
        return ids[0] if ids else None

    def test_healthy_self_report_is_accepted_but_not_attested(self):
        result = self.evaluate()
        self.assertEqual(self.assigned(result), 2)
        self.assertEqual(result["decision_status"], "ACCEPT")
        self.assertEqual(result["decisions"][2]["evidence_tier"], "signed_self_report_only")

    def test_position_age_is_independent_of_heartbeat_age(self):
        last_position = {i: self.t for i in self.members}
        last_position[2] = self.t - 7.
        result = self.evaluate(pseen=last_position)
        self.assertEqual(self.assigned(result), 1)
        self.assertEqual(result["decisions"][2]["action"], "REQUEST_FRESH_EVIDENCE")
        self.assertEqual(result["decisions"][2]["reason"], "stale_health_or_position")

    def test_unbounded_motion_jump_rejected(self):
        earlier = {2: ((220., 0., 10.), self.t - 0.1)}
        result = self.evaluate(prior=earlier)
        self.assertEqual(self.assigned(result), 1)
        self.assertEqual(result["decisions"][2]["reason"], "implausible_position_jump")

    def test_witnessed_false_health_rejected_and_honest_neighbor_used(self):
        self.health[2] = HealthReport(99., 100., 99.)
        independent_observation = {**self.health, 2: HealthReport(15., 60., 50.)}
        witness_map = {
            member: [
                sign_witness(self.members[reporter], subject_id=member,
                             epoch=1, observed_at=self.t,
                             health=independent_observation[member])
                for reporter in self.members if reporter != member
            ][:2]
            for member in self.members
        }
        result = self.evaluate(
            policy=ConsistencyPolicy(min_health_witnesses=2),
            witnesses=witness_map,
        )
        self.assertEqual(result["decisions"][2]["action"], "REJECT")
        self.assertEqual(result["decisions"][2]["reason"], "signed_witness_conflict")
        self.assertEqual(self.assigned(result), 1)
        self.assertEqual(result["decisions"][1]["evidence_tier"], "independently_corroborated")

    def test_claim_without_witness_cannot_be_verified(self):
        result = self.evaluate(policy=ConsistencyPolicy(min_health_witnesses=2))
        self.assertIsNone(self.assigned(result))
        self.assertEqual(result["decision_status"], "ABSTAIN")
        self.assertEqual(result["unassigned"], ["inspection"])
        self.assertEqual(result["decisions"][2]["reason"], "independent_evidence_insufficient")

    def test_tampered_self_and_stale_witness_cannot_count(self):
        good = sign_witness(
            self.members[3], subject_id=2, epoch=1, observed_at=self.t,
            health=self.health[2])
        tampered = replace(good, health=HealthReport(1., 1., 1.))
        expired = sign_witness(
            self.members[4], subject_id=2, epoch=1, observed_at=self.t - 10,
            health=self.health[2])
        from_old_view = sign_witness(
            self.members[4], subject_id=2, epoch=0, observed_at=self.t,
            health=self.health[2])
        self_report = sign_witness(
            self.members[2], subject_id=2, epoch=1, observed_at=self.t,
            health=self.health[2])
        result = self.evaluate(
            policy=ConsistencyPolicy(min_health_witnesses=2),
            witnesses={2: [good, tampered, expired, from_old_view, self_report, good]},
        )
        self.assertEqual(result["decisions"][2]["health_witnesses"], 1)
        self.assertEqual(result["decisions"][2]["reason"], "independent_evidence_insufficient")

    def test_valid_position_witness_conflict_blocks_member(self):
        witness = sign_witness(
            self.members[3], subject_id=2, epoch=1, observed_at=self.t,
            position=(80., 0., 10.), position_uncertainty_m=1.)
        result = self.evaluate(witnesses={2: [witness]})
        self.assertEqual(result["decisions"][2]["reason"], "signed_witness_conflict")
        self.assertEqual(self.assigned(result), 1)

    def test_position_witness_age_and_speed_allow_bounded_motion(self):
        witness = sign_witness(
            self.members[3], subject_id=2, epoch=1, observed_at=self.t-0.2,
            position=(3., 0., 10.), position_uncertainty_m=0.4)
        result = self.evaluate(
            policy=ConsistencyPolicy(min_position_witnesses=1),
            witnesses={2:[witness]},
        )
        self.assertEqual(result["decisions"][2]["action"], "ACCEPT")
        self.assertEqual(result["decisions"][2]["position_witnesses"], 1)

    def test_invalid_inputs_are_fail_closed(self):
        nan_position = {**self.positions, 2: (float("nan"), 0., 10.)}
        self.assertEqual(self.evaluate(positions=nan_position)["decisions"][2]["action"], "REJECT")
        self.assertEqual(self.evaluate(prior={2: ((1.,0.,10.), self.t+1.)})
                         ["decisions"][2]["reason"], "invalid_position_history")
        with self.assertRaises(ValueError):
            ConsistencyPolicy(max_health_age_s=float("inf"))
        with self.assertRaises(ValueError):
            ConsistencyPolicy(min_health_witnesses=-1)
        with self.assertRaises(ValueError):
            sign_witness(self.members[3], subject_id=2, epoch=1,
                         observed_at=float("nan"), health=self.health[2])


class CertifiedPathTests(unittest.TestCase):
    def setUp(self):
        points = {1:(60.,0.),2:(0.,0.),3:(100.,0.),4:(130.,0.)}
        self.drones = {i:Drone(i,Position(*pos,0.)) for i,pos in points.items()}
        self.sim = DroneMeshSimulation(self.drones, heartbeat_timeout_s=5.)
        self.clock = ManualClock()
        for node in self.sim.nodes.values():
            node.clock = self.clock
            node.channel.clock = self.clock
        self.network = InMemoryMesh(list(self.sim.nodes.values()))
        self.positions = {i:(*p,10.) for i,p in points.items()}
        self.health = {i: HealthReport(90.,100.,95.) for i in points}
        self.task = {"inspection":(1.,0.,10.)}

    def tearDown(self):
        self.sim.stop()
        for drone in self.drones.values():
            if drone.running:
                drone.stop()

    def broadcast(self, *, missing_position_for=()):
        for node_id in sorted(self.sim.nodes):
            position = None if node_id in missing_position_for else self.positions[node_id]
            packet = self.sim.nodes[node_id].publish_health(self.health[node_id], position)
            self.network.broadcast(node_id, packet)

    def elect(self):
        ballots = [(i,node.begin_election(candidate=1))
                   for i,node in sorted(self.sim.nodes.items())]
        for node_id,packet in ballots:
            self.network.broadcast(node_id,packet)
        self.assertEqual(self.sim.leader(),1)

    def test_real_signed_heartbeat_health_only_refresh_does_not_refresh_xyz(self):
        self.broadcast()
        self.clock.now += 7.
        self.broadcast(missing_position_for=(2,))
        self.assertEqual(self.sim.nodes[1].positions_seen_at[2],1000.)
        self.assertEqual(self.sim.nodes[1].health[2][1],1007.)
        self.elect()
        baseline = self.sim.command_tasks(self.task)
        gated = self.sim.command_tasks(self.task,consistency_policy=ConsistencyPolicy())
        self.assertIn("2",baseline["assigned"])
        self.assertIn("1",gated["assigned"])
        self.assertEqual(gated["telemetry_decisions"][2]["reason"],"stale_health_or_position")
        self.assertNotIn("telemetry_decisions",baseline)

    def test_certified_allocation_with_signed_independent_health_reports(self):
        # Node 2 owns the valid signing key yet reports falsely healthy status.
        # Peer witnesses are modeled as independently measuring the simulated
        # true health state; the gate receives only signed peer claims.
        independently_observed = dict(self.health)
        independently_observed[2] = HealthReport(15.,60.,50.)
        self.health[2] = HealthReport(99.,100.,99.)
        self.broadcast()
        self.elect()
        witness_map = {
            subject:[
                sign_witness(self.sim._identities[reporter],subject_id=subject,
                             epoch=1,observed_at=self.clock.now,
                             health=independently_observed[subject])
                for reporter in sorted(self.sim.nodes) if reporter!=subject
            ][:2]
            for subject in sorted(self.sim.nodes)
        }
        baseline = self.sim.command_tasks(self.task)
        guarded = self.sim.command_tasks(
            self.task,consistency_policy=ConsistencyPolicy(min_health_witnesses=2),
            witnesses=witness_map)
        self.assertIn("2",baseline["assigned"])
        self.assertIn("1",guarded["assigned"])
        self.assertEqual(guarded["telemetry_decisions"][2]["reason"],"signed_witness_conflict")
        self.assertGreaterEqual(self.sim.audit_ledgers[1].height,2)

    def test_unsigned_witnesses_cannot_bypass_opt_in(self):
        self.broadcast()
        self.elect()
        w=sign_witness(self.sim._identities[3],subject_id=2,epoch=1,
                       observed_at=self.clock.now,health=self.health[2])
        with self.assertRaises(ValueError):
            self.sim.command_tasks(self.task,witnesses={2:[w]})


